class TestContext:

    def __init__(self):
        self._variables = {}

    # ======================================================
    # SET
    # ======================================================

    def set(self, key, value):
        self._variables[key] = value

    # ======================================================
    # GET
    # ======================================================

    def get(self, key, default=None):
        return self._variables.get(
            key,
            default
        )

    # ======================================================
    # HAS
    # ======================================================

    def has(self, key):
        return key in self._variables

    # ======================================================
    # REMOVE
    # ======================================================

    def remove(self, key):
        self._variables.pop(
            key,
            None
        )

    # ======================================================
    # CLEAR
    # ======================================================

    def clear(self):
        self._variables.clear()

    # ======================================================
    # ALL
    # ======================================================

    def all(self):
        return self._variables.copy()